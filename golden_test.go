package names_test

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"

	names "github.com/improbabilitea/names-go"
	"github.com/improbabilitea/names-go/filters/reserved"
	"github.com/improbabilitea/names-go/packs/cinema"
	"github.com/improbabilitea/names-go/packs/common"
)

var update = flag.Bool("update", false, "rewrite the golden files instead of comparing against them")

// The golden files are where the determinism contract becomes something CI can
// enforce. Every seeded name the library will ever produce depends on the pack
// fingerprint, and a vocabulary edit moves it — so these files record both, and a
// diff says which of the two changed.
//
// When a change is intended, regenerate with:
//
//	go test -run Golden -update ./...
//
// and read the diff before committing it. A moved fingerprint means every seeded
// name in every consumer's database has just stopped being reproducible, which
// is a release note, not a rubber stamp.

type goldenCase struct {
	name    string
	options []names.Option
}

func goldenCases() []goldenCase {
	return []goldenCase{
		{
			name:    "common-username",
			options: []names.Option{names.WithPack(common.Pack)},
		},
		{
			name: "common-cinema-username",
			options: []names.Option{
				names.WithPack(common.Pack, names.PackWeight(1)),
				names.WithPack(cinema.Pack, names.PackWeight(4)),
			},
		},
		{
			name: "common-cinema-slug-constrained",
			options: []names.Option{
				names.WithPack(common.Pack, names.PackWeight(1)),
				names.WithPack(cinema.Pack, names.PackWeight(4)),
				names.WithFormat(names.Slug),
				names.WithMinLength(5),
				names.WithMaxLength(24),
				names.WithCharset(names.CharsetSlug),
				names.WithReservedWords(reserved.Default),
			},
		},
		{
			name: "common-display-name",
			options: []names.Option{
				names.WithPack(common.Pack),
				names.WithFormat(names.DisplayName),
				names.WithMaxLength(60),
			},
		},
	}
}

var goldenSeeds = []string{
	"42",
	"user_01893",
	"",
	"a",
	"angelo@example.com",
	"00000000-0000-0000-0000-000000000000",
	"ünïcødé",
	strings.Repeat("long", 64),
}

func TestGolden(t *testing.T) {
	for _, tc := range goldenCases() {
		t.Run(tc.name, func(t *testing.T) {
			g, err := names.New(tc.options...)
			if err != nil {
				t.Fatalf("New: %v", err)
			}

			got := renderGolden(t, g)
			path := filepath.Join("testdata", "golden", tc.name+".txt")

			if *update {
				if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
					t.Fatalf("creating the golden directory: %v", err)
				}
				if err := os.WriteFile(path, []byte(got), 0o600); err != nil {
					t.Fatalf("writing %s: %v", path, err)
				}
				t.Logf("wrote %s", path)
				return
			}

			wantBytes, err := os.ReadFile(path) //#nosec G304 -- a fixed test path
			if err != nil {
				t.Fatalf("reading %s: %v (run `go test -run Golden -update` to create it)", path, err)
			}

			if want := string(wantBytes); got != want {
				reportGoldenDiff(t, tc.name, want, got)
			}
		})
	}
}

func renderGolden(t *testing.T, g *names.Generator) string {
	t.Helper()

	var b strings.Builder
	b.WriteString("# Generated by `go test -run Golden -update`. Do not edit by hand.\n")
	b.WriteString("#\n")
	b.WriteString("# The fingerprint identifies the pack set. If it moved, the vocabulary\n")
	b.WriteString("# changed and every seeded name below changed with it.\n\n")

	fmt.Fprintf(&b, "fingerprint %s\n\n", g.Fingerprint())

	for _, seed := range goldenSeeds {
		result, err := g.Generate(names.Seed(seed))
		if err != nil {
			fmt.Fprintf(&b, "%-24q ERROR %v\n", seed, err)
			continue
		}
		fmt.Fprintf(&b, "%-24q %s\n", seed, result.Value)
	}

	return b.String()
}

// reportGoldenDiff explains *what* changed rather than dumping two blobs: the
// fingerprint line is the one that tells a reader whether this was a vocabulary
// edit or an algorithm change.
func reportGoldenDiff(t *testing.T, name, want, got string) {
	t.Helper()

	wantPrint := fingerprintLine(want)
	gotPrint := fingerprintLine(got)

	switch {
	case wantPrint != gotPrint:
		t.Errorf("%s: the pack fingerprint moved\n  was: %s\n  now: %s\n\n"+
			"The vocabulary or the pack weights changed, so every seeded name changed too. "+
			"If that was intended, regenerate with `go test -run Golden -update` and note it in the changelog.",
			name, wantPrint, gotPrint)
	default:
		t.Errorf("%s: same fingerprint (%s) but different names.\n\n"+
			"The vocabulary is unchanged, so this is a selection-algorithm change — "+
			"which breaks reproducibility without any signal a consumer could detect. "+
			"Bump algorithmVersion, or revert.\n\nwant:\n%s\ngot:\n%s",
			name, wantPrint, want, got)
	}
}

func fingerprintLine(golden string) string {
	for _, line := range strings.Split(golden, "\n") {
		if after, ok := strings.CutPrefix(line, "fingerprint "); ok {
			return after
		}
	}
	return "(none)"
}
